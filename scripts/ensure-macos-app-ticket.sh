#!/usr/bin/env bash
set -euo pipefail

: "${GITHUB_WORKSPACE:?}"
: "${RUNNER_TEMP:?}"
: "${GITHUB_ENV:?}"
: "${RELEASE_VERSION:?}"
: "${APPLE_SIGNING_IDENTITY:?}"
: "${EDUPI_RESOURCE_KEYCHAIN_PATH:?}"
: "${TAURI_SIGNING_PRIVATE_KEY:?}"

bundle_root="$GITHUB_WORKSPACE/src-tauri/target/aarch64-apple-darwin/release/bundle"
mac_dir="$bundle_root/macos"
dmg_dir="$bundle_root/dmg"
app="$mac_dir/EduPi.app"
dmg_name="EduPi_${RELEASE_VERSION}_aarch64.dmg"
dmg="$dmg_dir/$dmg_name"
updater="$mac_dir/EduPi.app.tar.gz"

test -d "$app"
test -f "$dmg"
test -f "$updater"
test -f "$updater.sig"
test -f "$dmg_dir/bundle_dmg.sh"
codesign --verify --deep --strict --verbose=2 "$app"

if node scripts/validate-macos-staple.mjs "$app" > "$RUNNER_TEMP/edupi-app-ticket-before.log" 2>&1; then
  printf 'EDUPI_MAC_APP_REPACKED=0\n' >> "$GITHUB_ENV"
  echo "The signed App already has a validated notarization ticket."
  exit 0
fi

# Tauri CLI 2.11.4 can print "Stapling app..." while discarding stapler's
# exit status. The existing accepted submission must yield a real ticket here.
node scripts/staple-macos-artifact.mjs "$app"
node scripts/validate-macos-staple.mjs "$app"
codesign --verify --deep --strict --verbose=2 "$app"
spctl --assess --type execute --verbose=2 "$app"

# Both the DMG and updater tar were made before the ticket was attached.
# Preserve their original generated bytes for this CI attempt and repackage
# both from the same now-stapled App before any final asset is accepted.
test ! -e "$RUNNER_TEMP/edupi-dmg-before-app-ticket.dmg"
test ! -e "$RUNNER_TEMP/edupi-updater-before-app-ticket.tar.gz"
test ! -e "$RUNNER_TEMP/edupi-updater-before-app-ticket.sig"
mv "$dmg" "$RUNNER_TEMP/edupi-dmg-before-app-ticket.dmg"
mv "$updater" "$RUNNER_TEMP/edupi-updater-before-app-ticket.tar.gz"
mv "$updater.sig" "$RUNNER_TEMP/edupi-updater-before-app-ticket.sig"

(
  cd "$mac_dir"
  "$dmg_dir/bundle_dmg.sh" \
    --volname EduPi --icon EduPi.app 180 170 \
    --app-drop-link 480 170 --window-size 660 400 \
    --hide-extension EduPi.app --volicon "$dmg_dir/icon.icns" \
    "$dmg_name" EduPi.app
)
test -f "$mac_dir/$dmg_name"
mv "$mac_dir/$dmg_name" "$dmg"
codesign --force --sign "$APPLE_SIGNING_IDENTITY" --keychain "$EDUPI_RESOURCE_KEYCHAIN_PATH" "$dmg"
codesign --verify --verbose=2 "$dmg"

COPYFILE_DISABLE=1 tar -czf "$updater" -C "$mac_dir" EduPi.app
node_modules/.bin/tauri signer sign "$updater"
test -s "$updater"
test -s "$updater.sig"
printf 'EDUPI_MAC_APP_REPACKED=1\n' >> "$GITHUB_ENV"
echo "Repacked the signed DMG and updater archive from the validated stapled App."
